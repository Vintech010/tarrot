function detect(patterns, question, fallback) {
  return patterns.find(([, pattern]) => pattern.test(question))?.[0] ?? fallback;
}

function getReadingSetup(topicChoice, intentChoice, rawQuestion) {
  const question = rawQuestion.trim().replace(/\s+/g, ' ');
  const topicId = topicChoice === 'auto' ? detect(topicPatterns, question, 'general') : topicChoice;
  const intentId = intentChoice === 'auto' ? detect(intentPatterns, question, 'overview') : intentChoice;
  const topic = topics[topicId];
  const intent = intents[intentId];

  return {
    topicId,
    intentId,
    topic,
    intent,
    question,
    example: topic.examples[intent.index],
  };
}

function getReadingContext(card, reversed, setup) {
  const { topic, topicId, intent, question } = setup;
  const scenario = scenarios[topicId]?.find(([pattern]) => pattern.test(question));
  const lens = scenario?.[1] ?? topic.lenses[card.group];
  const lead = reversed ? intent.reversed : intent.lead;
  return {
    focus: lead + ' ' + lens,
    prompt: topic.prompts[intent.index],
  };
}

